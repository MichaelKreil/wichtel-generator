export const CODE_NAME_LISTS: readonly CodeNameList[] = LISTS;

export const DEFAULT_LIST_ID = 'schauspiel';

const byId = new Map(CODE_NAME_LISTS.map((list) => [list.id, list]));

export function getCodeNameList(id: unknown): CodeNameList | undefined {
	return typeof id === 'string' ? byId.get(id) : undefined;
}

/** The names of a list; unknown ids (e.g. of removed lists) fall back to the default list. */
export function codeNamesFor(listId: string): readonly string[] {
	return (byId.get(listId) ?? (byId.get(DEFAULT_LIST_ID) as CodeNameList)).names;
}
