/** All lists together. Also used by pots created before lists could be chosen. */
export const MIXED_LIST: CodeNameList = {
	id: 'gemischt',
	label: 'Alle gemischt',
	names: [...new Set(LISTS.flatMap((list) => list.names))],
};

export const CODE_NAME_LISTS: readonly CodeNameList[] = [...LISTS, MIXED_LIST];

export const DEFAULT_LIST_ID = 'plaetzchen';

const byId = new Map(CODE_NAME_LISTS.map((list) => [list.id, list]));

export function getCodeNameList(id: unknown): CodeNameList | undefined {
	return typeof id === 'string' ? byId.get(id) : undefined;
}

/** The names of a list; unknown ids fall back to all names. */
export function codeNamesFor(listId: string): readonly string[] {
	return (byId.get(listId) ?? MIXED_LIST).names;
}
