// Writes public/static/themes.css from src/themes.ts, then src/asset-version.ts with a hash of the CSS/JS,
// so browsers load them again after every change. Run after changing themes, CSS or JS: npm run assets
import { writeFileSync } from 'node:fs';
import { themesCss } from '../src/themes.ts';
import { assetVersion } from './lib/assets.ts';

writeFileSync(new URL('../public/static/themes.css', import.meta.url), `${themesCss()}\n`);
const version = assetVersion();
writeFileSync(
	new URL('../src/asset-version.ts', import.meta.url),
	`// Generated by \`npm run assets\`: a hash of style.css, app.js and themes.css, used as ?v= in their URLs.\nexport const ASSET_VERSION = '${version}';\n`,
);
console.log(`wrote public/static/themes.css and src/asset-version.ts (${version})`);
